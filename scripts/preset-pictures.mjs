// The pictures of the built-in presets, drawn for the project (spec §11: no
// third-party images): a five-pointed star for the medal, a logo (a peak
// in a ring) for the name plate and an apple for the fridge magnet. Writes them as grayscale + alpha PNG data
// URLs, the stored picture format, into src/state/presetPictures.ts.
//
//   node scripts/preset-pictures.mjs
//
// Run it again only to change a picture; the output is committed.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { deflateSync } from 'node:zlib';

const SIZE = 128;

const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([Buffer.from(type, 'ascii'), data])), 0);
  return Buffer.concat([head, data, crc]);
}

/** A gray + alpha PNG from a function of the pixel centre (u, v in −1…1, v up) → [gray, alpha] 0…1. */
function png(shade) {
  const rows = [];
  for (let j = 0; j < SIZE; j++) {
    const row = Buffer.alloc(1 + SIZE * 2);
    for (let i = 0; i < SIZE; i++) {
      const [g, a] = shade(((i + 0.5) / SIZE) * 2 - 1, 1 - ((j + 0.5) / SIZE) * 2);
      row[1 + i * 2] = Math.round(255 * Math.min(1, Math.max(0, g)));
      row[2 + i * 2] = Math.round(255 * Math.min(1, Math.max(0, a)));
    }
    rows.push(row);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(SIZE, 0);
  ihdr.writeUInt32BE(SIZE, 4);
  ihdr[8] = 8;
  ihdr[9] = 4; // gray + alpha
  const file = Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(Buffer.concat(rows))),
    chunk('IEND', Buffer.alloc(0)),
  ]);
  return `data:image/png;base64,${file.toString('base64')}`;
}

/** Coverage of a shape from its signed distance (negative inside), in pixels of a 2-unit-wide picture. */
const cover = (d) => Math.min(1, Math.max(0, 0.5 - (d * SIZE) / 2));

/** A star polygon of n points (outer R, inner r), a point up. */
function starPolygon(n, R, r) {
  return Array.from({ length: 2 * n }, (_, k) => {
    const a = Math.PI / 2 + (Math.PI * k) / n;
    const radius = k % 2 ? r : R;
    return [radius * Math.cos(a), radius * Math.sin(a)];
  });
}

function inside([x, y], polygon) {
  let hit = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Coverage of a polygon over the pixel at (u, v), sampled 4 × 4. */
function coverage(u, v, polygon) {
  const step = 2 / SIZE / 4;
  let n = 0;
  for (let a = 0; a < 4; a++) for (let b = 0; b < 4; b++) if (inside([u + (a - 1.5) * step, v + (b - 1.5) * step], polygon)) n++;
  return n / 16;
}

const STAR = starPolygon(5, 0.97, 0.4);
// the star: white at its middle, falling to mid-gray at its tips, so the relief domes
const medal = png((u, v) => [1 - 0.5 * Math.min(1, Math.hypot(u, v) / 0.97), coverage(u, v, STAR)]);

// the logo: a ring (full height) around a peak (rising to the top)
const logo = png((u, v) => {
  const r = Math.hypot(u, v);
  const ring = Math.max(r - 0.95, 0.8 - r);
  const peak = Math.max(v - 0.45 + Math.abs(u) * 1.4, -0.55 - v, Math.abs(u) - 0.7);
  const inRing = cover(ring);
  const inPeak = cover(peak);
  return [Math.max(inRing, 0.55 + 0.45 * ((v + 0.55) / 1)), Math.max(inRing, inPeak)];
});

// the apple: two domed lobes, a stem and a leaf touching it
const apple = png((u, v) => {
  const body = Math.min(Math.hypot(u - 0.3, v + 0.1) - 0.6, Math.hypot(u + 0.3, v + 0.1) - 0.6);
  const stem = Math.max(Math.abs(u - 0.02) - 0.04, Math.abs(v - 0.62) - 0.14);
  // an ellipse turned 30°, its distance roughly: scaled by the short axis
  const [x, y] = [u - 0.28, v - 0.72];
  const [lx, ly] = [x * Math.cos(Math.PI / 6) + y * Math.sin(Math.PI / 6), -x * Math.sin(Math.PI / 6) + y * Math.cos(Math.PI / 6)];
  const leaf = (Math.hypot(lx / 0.24, ly / 0.1) - 1) * 0.1;
  const dome = 0.55 + 0.45 * (1 - Math.min(1, Math.hypot(u, v + 0.1) / 0.9));
  const [inBody, inStem, inLeaf] = [cover(body), cover(stem), cover(leaf)];
  return [inBody >= Math.max(inStem, inLeaf) ? dome : inLeaf >= inStem ? 0.85 : 0.7, Math.max(inBody, inStem, inLeaf)];
});

const out = `// Generated by scripts/preset-pictures.mjs: pictures drawn for the project, grayscale + alpha PNG.

/** A five-pointed star, domed (the medal). */
export const STAR_PICTURE = '${medal}';

/** A peak in a ring (the name plate's logo). */
export const LOGO_PICTURE = '${logo}';

/** An apple with a stem and a leaf, domed (the fridge magnet). */
export const APPLE_PICTURE = '${apple}';

/** All are this many pixels square. */
export const PRESET_PICTURE_PX = ${SIZE};
`;
writeFileSync(resolve(import.meta.dirname, '../src/state/presetPictures.ts'), out);
console.log(`star ${medal.length} chars, logo ${logo.length} chars, apple ${apple.length} chars`);
